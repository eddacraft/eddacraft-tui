//! INTD-001 (proto half): wire types shared by the Anvil intercept
//! daemon, launcher, and future drivers.
//!
//! Scope kept deliberately narrow for the A1 scaffold: identifiers,
//! the IPC command enum, and the NDJSON envelope. Session-state
//! structs, fence shapes, and full enforcement-decision payloads
//! arrive with INTD-003 and INTD-005 — landing them here pre-empts
//! design choices that should fall out of the daemon implementation.
//!
//! See `plans/modules/intercept-daemon.aps.md` and
//! `plans/decisions/015-intercept-loop-enforcement.md`.

#![forbid(unsafe_code)]

use serde::{Deserialize, Serialize};

/// Stable identifier for an intercept session.
///
/// Generated by the launcher when a new agent process is registered;
/// opaque to the daemon. Wire format is a string so future ID schemes
/// (UUID v7, ULID, etc.) can land without a proto break.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct SessionId(pub String);

impl SessionId {
    /// Construct a session id from any string-like value. No validation:
    /// the daemon is the single authority on uniqueness.
    pub fn new(id: impl Into<String>) -> Self {
        Self(id.into())
    }

    /// Borrow the underlying string.
    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

/// IPC commands the launcher and drivers send to the daemon over
/// NDJSON. The minimal A1 set; additional variants will land with
/// INTD-002 (IPC listener) and INTD-003 (session registry).
///
/// Tagged externally as `{ "command": "register-session", ... }` so
/// future variants can carry arbitrary payloads without ambiguity.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "command", rename_all = "kebab-case")]
pub enum IpcCommand {
    /// Register a new session with the daemon. Carries the session id
    /// only at this stage; richer process / worktree fields land with
    /// INTD-003.
    RegisterSession {
        session_id: SessionId,
    },
    /// Heartbeat from a registered session to refresh its liveness TTL
    /// (INTD-003 will enforce a 30 s default).
    Heartbeat {
        session_id: SessionId,
    },
    /// Unregister a session, releasing it from the registry.
    UnregisterSession {
        session_id: SessionId,
    },
    /// List all currently registered sessions. Diagnostic / status
    /// query — used by `anvil intercept status` (INTD-011) and the
    /// launcher's reconciliation flow.
    ListSessions,
}

/// Single NDJSON envelope. One line on the wire = one envelope. The
/// optional `id` carries the JSON-RPC-style request correlation token
/// so daemon responses can be matched back to launcher requests.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct IpcEnvelope {
    /// Optional correlation id. `None` means a notification (no
    /// response expected).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub id: Option<String>,
    /// The command payload.
    #[serde(flatten)]
    pub command: IpcCommand,
}

impl IpcEnvelope {
    /// Build a notification envelope (no `id`).
    #[must_use]
    pub fn notification(command: IpcCommand) -> Self {
        Self { id: None, command }
    }

    /// Build a request envelope with a correlation id.
    pub fn request(id: impl Into<String>, command: IpcCommand) -> Self {
        Self {
            id: Some(id.into()),
            command,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn session_id_round_trips_string() {
        let id = SessionId::new("sess_abc123");
        assert_eq!(id.as_str(), "sess_abc123");
    }

    #[test]
    fn register_session_envelope_serialises_to_ndjson_shape() {
        let envelope = IpcEnvelope::request(
            "req-1",
            IpcCommand::RegisterSession {
                session_id: SessionId::new("sess_abc"),
            },
        );

        let line = serde_json::to_string(&envelope).expect("serialise");
        let parsed: serde_json::Value = serde_json::from_str(&line).expect("parse back");
        assert_eq!(parsed["id"], "req-1");
        assert_eq!(parsed["command"], "register-session");
        assert_eq!(parsed["session_id"], "sess_abc");
    }

    #[test]
    fn heartbeat_notification_omits_id_field() {
        let envelope = IpcEnvelope::notification(IpcCommand::Heartbeat {
            session_id: SessionId::new("sess_abc"),
        });

        let line = serde_json::to_string(&envelope).expect("serialise");
        assert!(
            !line.contains("\"id\""),
            "notifications must not include an id field, got: {line}",
        );
    }

    #[test]
    fn list_sessions_round_trips() {
        let envelope = IpcEnvelope::request("req-list", IpcCommand::ListSessions);
        let line = serde_json::to_string(&envelope).expect("serialise");
        let back: IpcEnvelope = serde_json::from_str(&line).expect("deserialise");
        assert_eq!(back, envelope);
    }

    #[test]
    fn ipc_command_uses_kebab_case_discriminator() {
        let unreg = serde_json::to_string(&IpcCommand::UnregisterSession {
            session_id: SessionId::new("x"),
        })
        .expect("serialise");
        assert!(unreg.contains("\"unregister-session\""), "got: {unreg}");
    }
}
