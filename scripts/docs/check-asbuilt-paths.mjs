#!/usr/bin/env node
// Surface validator: runbook/as-built source path freshness.
//
// Validates governed As-built and Runbook documents that successfully parse via
// @eddacraft/anvil-docs-meta. Legacy documents without DOCGOV metadata remain
// owned by the metadata surface until DOCGOV-009 backfills them.

import { lstat, readFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { resolve, isAbsolute, relative as relPath, sep } from 'node:path';
import { parseArgs } from 'node:util';
import globby from 'globby';
import { parseDocGovernance, ParseError } from '@eddacraft/anvil-docs-meta';

const SURFACE = 'asbuilt-paths';

// DOCFRESH-004 widens this beyond As-built/Runbook. The two rules it carries —
// cited paths must resolve, and the document must cite at least one — are what
// make a document visible to the `docs-owed` freshness surface, so any type
// left out is a type that can declare nothing and still read as clean.
//
// Guide, Policy and Spec join. README deliberately does not: those are local
// orientation pages whose job is to point at siblings, and demanding a source
// pin from them would be governance for its own sake.
//
// Documents whose upstream is genuinely external — vision and strategy pieces
// derived from human intent, or third-party projects not vendored here — cannot
// satisfy "cite at least one path" and must not be made to fake one. They are
// absorbed into the baseline instead, which keeps them countable as known gaps
// rather than dressed up as covered.
const VALIDATED_TYPES = new Set(['As-built', 'Runbook', 'Guide', 'Policy', 'Spec']);

const { values } = parseArgs({
  options: {
    root: { type: 'string' },
    baseline: { type: 'string' },
    'no-baseline': { type: 'boolean', default: false },
    json: { type: 'boolean', default: false },
  },
  allowPositionals: false,
});

const root = resolve(values.root ?? process.cwd());
const baselinePath = resolve(root, values.baseline ?? 'docs/governance/docs-check.baseline.json');

let baseline = {};
if (!values['no-baseline'] && existsSync(baselinePath)) {
  try {
    const raw = await readFile(baselinePath, 'utf8');
    baseline = JSON.parse(raw)[SURFACE] ?? {};
  } catch (err) {
    process.stderr.write(`[${SURFACE}] failed to read baseline ${baselinePath}: ${err.message}\n`);
  }
}

const files = await globby(
  [
    'docs/**/*.md',
    '!docs/**/archive/**',
    '!docs/**/*.template.md',
    '!docs/**/*template.md',
    '!docs/**/README.md',
    // Generated by `pnpm docs:index` and regenerated wholesale, so there is no
    // human reviewer to carry a review date and no hand-authored upstream to
    // pin. Excluded when DOCFRESH-004 widened VALIDATED_TYPES, which otherwise
    // demanded both of them from every `docs/indexes/by-*.md`. The `docs-owed`
    // surface already excludes this directory for the same reason.
    '!docs/indexes/**',
  ],
  { cwd: root, gitignore: true }
);
files.sort();

const findings = [];
let filesChecked = 0;

await Promise.all(
  files.map(async (relFile) => {
    const absFile = resolve(root, relFile);
    let content;
    try {
      content = await readFile(absFile, 'utf8');
    } catch (err) {
      findings.push({
        severity: 'ERROR',
        file: relFile,
        line: 1,
        message: `failed to read file: ${err.message}`,
      });
      return;
    }

    let parsed;
    try {
      parsed = parseDocGovernance(content, relFile);
    } catch (err) {
      // Metadata shape is validated by the metadata surface; avoid duplicate
      // reporting here so DOCGOV-009 can backfill legacy docs incrementally.
      if (err instanceof ParseError) return;
      findings.push({
        severity: 'ERROR',
        file: relFile,
        line: 1,
        message: `unexpected parser failure: ${err.message}`,
      });
      return;
    }

    if (!VALIDATED_TYPES.has(parsed.metadata.type)) return;
    filesChecked += 1;

    if (!parsed.freshness.reviewedOn) {
      findings.push({
        severity: 'ERROR',
        file: relFile,
        line: parsed.sourceLineNumber ?? 1,
        message: 'freshness must include a YYYY-MM-DD review date',
      });
    }

    if (parsed.sourceReferences.length === 0) {
      findings.push({
        severity: 'ERROR',
        file: relFile,
        line: parsed.sourceLineNumber ?? 1,
        // Names the type rather than a fixed pair: DOCFRESH-004 widened
        // VALIDATED_TYPES beyond As-built/Runbook, and a message that still
        // said "as-built/runbook" would misreport every Guide, Policy and Spec
        // finding. Changing this text invalidates existing baseline
        // fingerprints, so the baseline is regenerated alongside it.
        message: `${parsed.metadata.type} document must cite at least one source path`,
      });
      return;
    }

    for (const ref of parsed.sourceReferences) {
      const result = await resolveSourcePath(ref.path);
      if (result) {
        findings.push({
          severity: 'ERROR',
          file: relFile,
          line: ref.line ?? parsed.sourceLineNumber ?? 1,
          message: `${result} (${ref.context} reference "${ref.path}")`,
        });
      }
    }
  })
);

async function resolveSourcePath(path) {
  if (path.includes('<') || path.includes('>') || path.includes('{') || path.includes('}'))
    return null;
  const normalised = path.replace(/#.*$/, '').replace(/:\d+(?:-\d+)?$/, '');
  // Containment is a precondition for filesystem expansion. Path resolution
  // is lexical, so glob metacharacters can stay in the probe while traversal
  // and absolute paths are rejected before globby observes the host tree.
  const targetAbs = resolve(root, normalised);
  const rel = relPath(root, targetAbs);
  if (rel.startsWith('..') || isAbsolute(rel))
    return `source path escapes repository root: "${path}"`;

  // Walk the already-normalised in-root path. Walking the raw reference would
  // let a missing component before a cancelling `..` stop inspection before
  // a later symlink that the resolved target actually traverses.
  const symlink = await symlinkInStaticPathPrefix(rel);
  if (symlink) {
    const kind = normalised.includes('*') ? 'glob' : 'path';
    return `source path ${kind} traverses symlink "${symlink}": "${path}"`;
  }

  if (normalised.includes('*')) {
    const matches = await globby([normalised], {
      cwd: root,
      gitignore: false,
      onlyFiles: false,
      followSymbolicLinks: false,
    });
    return matches.length === 0
      ? `source path glob does not match anything: "${normalised}"`
      : null;
  }

  if (!existsSync(targetAbs)) return `source path does not exist: "${normalised}"`;
  return null;
}

async function symlinkInStaticPathPrefix(relativeTarget) {
  const dynamicAt = relativeTarget.search(/[?*[{]/);
  const prefix = dynamicAt === -1 ? relativeTarget : relativeTarget.slice(0, dynamicAt);
  let current = root;
  for (const component of prefix.split(sep).filter(Boolean)) {
    current = resolve(current, component);
    try {
      if ((await lstat(current)).isSymbolicLink()) return relPath(root, current);
    } catch (error) {
      if (error?.code === 'ENOENT' || error?.code === 'ENOTDIR') return null;
      throw error;
    }
  }
  return null;
}

for (const finding of findings) {
  const fingerprints = baseline[finding.file];
  if (Array.isArray(fingerprints) && fingerprints.includes(finding.message)) {
    finding.severity = 'WARN';
    finding.message = `[baselined] ${finding.message}`;
  }
}

findings.sort((a, b) => a.file.localeCompare(b.file) || a.line - b.line);

const errors = findings.filter((f) => f.severity === 'ERROR').length;
const warnings = findings.filter((f) => f.severity === 'WARN').length;
const summary = { errors, warnings, filesChecked };

if (values.json) {
  process.stdout.write(`${JSON.stringify({ surface: SURFACE, findings, summary }, null, 2)}\n`);
} else {
  for (const f of findings) {
    process.stdout.write(`[${SURFACE}] ${f.severity}: ${f.file}:${f.line} — ${f.message}\n`);
  }
  process.stdout.write(
    `[${SURFACE}] summary: ${errors} errors, ${warnings} warnings, ${filesChecked} files checked\n`
  );
}

process.exit(errors > 0 ? 1 : 0);
