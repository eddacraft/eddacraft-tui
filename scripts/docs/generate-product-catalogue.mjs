#!/usr/bin/env node
// FLAGCAT-014: generate the human-readable product catalogue from
// flags/surfaces.json and flags/manifest.json. The generated markdown is a
// view, never a second source of truth.

import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import process from 'node:process';

const argv = process.argv.slice(2);
const WRITE = argv.includes('--write');
const CHECK = !WRITE;
const ROOT = resolve(fileURLToPath(new URL('../..', import.meta.url)));
const OUTPUT = resolve(ROOT, 'docs/guides/product-feature-catalogue.md');

function loadJson(relativePath) {
  return JSON.parse(readFileSync(resolve(ROOT, relativePath), 'utf8'));
}

function escapeCell(value) {
  return String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
}

function locatorLabel(locator) {
  switch (locator.kind) {
    case 'cli':
      return `cli ${locator.commandPath.join(' ')}`.trim();
    case 'mcp-tool':
      return `mcp-tool ${locator.name}`;
    case 'mcp-resource':
      return `mcp-resource ${locator.uri}`;
    case 'api-route':
      return `${locator.method} ${locator.path}`;
    case 'daemon-rpc':
      return `daemon ${locator.method}`;
    case 'dashboard-route':
      return `dashboard ${locator.path}`;
    case 'docs-route':
      return `docs ${locator.pathPrefix}`;
    case 'hook':
      return `hook ${locator.hook}`;
    case 'integration':
      return `integration ${locator.integrationId}/${locator.capability}`;
    default:
      return locator.kind;
  }
}

function linkageLabel(linkage, flagByKey) {
  if (linkage.disposition === 'unflagged') {
    return `unflagged — ${linkage.reason}`;
  }
  return linkage.flagKeys
    .map((key) => {
      const flag = flagByKey.get(key);
      return flag ? `${key} (${flag.class})` : key;
    })
    .join(', ');
}

function render() {
  const catalogue = loadJson('flags/surfaces.json');
  const manifest = loadJson('flags/manifest.json');
  const flagByKey = new Map(manifest.flags.map((flag) => [flag.key, flag]));
  const groupByKey = new Map(
    catalogue.productFeatureGroups.map((group) => [group.key, group])
  );

  const groups = [...catalogue.productFeatureGroups].sort((a, b) => a.key.localeCompare(b.key));
  const features = [...catalogue.productFeatures].sort((a, b) => a.key.localeCompare(b.key));
  const deliveries = [...catalogue.deliverySurfaces].sort((a, b) => a.key.localeCompare(b.key));
  const exclusions = [...catalogue.excludedDeliverySurfaces].sort((a, b) =>
    a.key.localeCompare(b.key)
  );
  const flags = [...manifest.flags].sort((a, b) => a.key.localeCompare(b.key));

  const lines = [
    '# Product feature catalogue',
    '',
    '| Type  | Authority | Owner   | Status | Freshness |',
    '| ----- | --------- | ------- | ------ | --------- |',
    '| Guide | Derived   | FLAGCAT | Live   | Generated from `flags/surfaces.json` and `flags/manifest.json` |',
    '',
    '| Upstream | Downstream |',
    '| -------- | ---------- |',
    '| `flags/surfaces.json`, `flags/manifest.json`, ADR-076 | Feature-flag guides, ADR-076 appendix |',
    '',
    '<!-- Generated by scripts/docs/generate-product-catalogue.mjs; do not edit by hand. -->',
    '',
    'This page is a generated view of the canonical product catalogue. Edit',
    '`flags/surfaces.json` and `flags/manifest.json`, then run',
    '`pnpm docs:catalogue:generate`. Do not maintain a second feature list.',
    '',
    `Schema version ${catalogue.schemaVersion}. ${features.length} product features,`,
    `${deliveries.length} delivery surfaces, ${exclusions.length} exclusions,`,
    `${flags.length} operational flags.`,
    '',
    '## Product feature groups',
    '',
    '| Key | Name | Default access | Status |',
    '| --- | ---- | -------------- | ------ |',
  ];

  for (const group of groups) {
    lines.push(
      `| \`${escapeCell(group.key)}\` | ${escapeCell(group.name)} | ${escapeCell(group.defaultSurfacePosture.access)} | ${escapeCell(group.status)} |`
    );
  }

  lines.push('', '## Product features', '', '| Key | Name | Group | Owner | Status | Flag linkage |', '| --- | ---- | ----- | ----- | ------ | ------------ |');

  for (const feature of features) {
    const group = groupByKey.get(feature.groupKey);
    lines.push(
      `| \`${escapeCell(feature.key)}\` | ${escapeCell(feature.name)} | ${escapeCell(group?.name ?? feature.groupKey)} | ${escapeCell(feature.owner)} | ${escapeCell(feature.status)} | ${escapeCell(linkageLabel(feature.flagLinkage, flagByKey))} |`
    );
  }

  lines.push(
    '',
    '## Delivery surfaces',
    '',
    '| Key | Feature | Locator | Status |',
    '| --- | ------- | ------- | ------ |'
  );
  for (const surface of deliveries) {
    lines.push(
      `| \`${escapeCell(surface.key)}\` | \`${escapeCell(surface.featureKey)}\` | ${escapeCell(locatorLabel(surface.locator))} | ${escapeCell(surface.status)} |`
    );
  }

  lines.push(
    '',
    '## Excluded internal plumbing',
    '',
    '| Key | Owner | Reason | Status |',
    '| --- | ----- | ------ | ------ |'
  );
  for (const surface of exclusions) {
    lines.push(
      `| \`${escapeCell(surface.key)}\` | ${escapeCell(surface.owner)} | ${escapeCell(surface.reason)} | ${escapeCell(surface.status)} |`
    );
  }

  lines.push(
    '',
    '## Operational flags',
    '',
    '| Key | Class | Controls | Status |',
    '| --- | ----- | -------- | ------ |'
  );
  for (const flag of flags) {
    const controls = (flag.controlsProductFeatures ?? []).join(', ') || '—';
    lines.push(
      `| \`${escapeCell(flag.key)}\` | ${escapeCell(flag.class)} | ${escapeCell(controls)} | ${escapeCell(flag.status)} |`
    );
  }

  lines.push('');
  return `${lines.join('\n')}\n`;
}

function formatMarkdown(content) {
  const directory = mkdtempSync(join(tmpdir(), 'product-catalogue-'));
  const file = join(directory, 'product-feature-catalogue.md');
  writeFileSync(file, content);
  const result = spawnSync('pnpm', ['exec', 'oxfmt', '--write', file], {
    cwd: ROOT,
    encoding: 'utf8',
  });
  if (result.status !== 0) {
    rmSync(directory, { recursive: true, force: true });
    throw new Error((result.stderr || result.stdout || 'oxfmt failed').trim());
  }
  const formatted = readFileSync(file, 'utf8');
  rmSync(directory, { recursive: true, force: true });
  return formatted;
}

const generated = formatMarkdown(render());
if (CHECK) {
  let current = '';
  try {
    current = readFileSync(OUTPUT, 'utf8');
  } catch {
    current = '';
  }
  if (current !== generated) {
    process.stderr.write(
      `[product-catalogue] ${OUTPUT} is stale; run pnpm docs:catalogue:generate\n`
    );
    process.exit(1);
  }
  process.stdout.write('[product-catalogue] generated catalogue view is current\n');
  process.exit(0);
}

writeFileSync(OUTPUT, generated);
process.stdout.write(`[product-catalogue] wrote ${OUTPUT}\n`);
