#!/usr/bin/env node
// Generated documentation indexes (DOCGOV-007).
//
// Scans governed Markdown files, parses document-local DOCGOV metadata, and
// emits deterministic discovery indexes. `--check` compares the expected output
// with files on disk so docs-check can fail when generated indexes are stale.

import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { mkdirSync } from 'node:fs';
import { parseArgs } from 'node:util';
import globby from 'globby';
import { unified } from 'unified';
import remarkParse from 'remark-parse';
import remarkGfm from 'remark-gfm';
import { visit } from 'unist-util-visit';
import { parseDocGovernance, ParseError } from '@eddacraft/anvil-docs-meta';

const SURFACE = 'index-freshness';
const GENERATED_MARKER = '<!-- Generated by scripts/docs/docs-index.mjs; do not edit by hand. -->';
const INDEX_DIR = 'docs/indexes';
const INDEX_FILES = [
  'README.md',
  'by-type.md',
  'by-authority.md',
  'by-owner.md',
  'by-status.md',
  'by-tag.md',
];
const SOURCE_PATTERNS = [
  'docs/**/*.md',
  '!docs/**/archive/**',
  '!docs/**/*.template.md',
  '!docs/indexes/**',
];
const TAG_LINE_RE = /^(?:- )?\*\*Tags:\*\*\s*(.+)$/gm;

const { values } = parseArgs({
  options: {
    root: { type: 'string' },
    check: { type: 'boolean', default: false },
    json: { type: 'boolean', default: false },
  },
  allowPositionals: false,
});

const root = resolve(values.root ?? process.cwd());
const findings = [];
const docs = await collectDocs(root);
const approvedTags = await collectApprovedTags(root);
const outputs = renderIndexes(docs, approvedTags);

if (values.check) {
  await checkOutputs(outputs);
} else {
  await writeOutputs(outputs);
}

const errors = findings.filter((f) => f.severity === 'ERROR').length;
const warnings = findings.filter((f) => f.severity === 'WARN').length;
const summary = { errors, warnings, filesChecked: INDEX_FILES.length };

if (values.json) {
  process.stdout.write(
    `${JSON.stringify(
      {
        surface: SURFACE,
        findings: findings.map((f) => ({
          severity: f.severity,
          file: f.file,
          line: f.line,
          message: f.message,
        })),
        summary,
      },
      null,
      2
    )}\n`
  );
} else {
  for (const f of findings) {
    process.stdout.write(`[${SURFACE}] ${f.severity}: ${f.file}:${f.line} — ${f.message}\n`);
  }
  process.stdout.write(
    `[${SURFACE}] summary: ${errors} errors, ${warnings} warnings, ${INDEX_FILES.length} files checked\n`
  );
}

process.exit(errors > 0 ? 1 : 0);

async function collectDocs(repoRoot) {
  const files = await globby(SOURCE_PATTERNS, { cwd: repoRoot, gitignore: true });
  files.sort();
  const parsed = [];

  await Promise.all(
    files.map(async (relPath) => {
      const content = await readFile(resolve(repoRoot, relPath), 'utf8');
      try {
        const governance = parseDocGovernance(content, relPath);
        parsed.push({
          path: relPath,
          title: governance.title,
          type: governance.metadata.type,
          authority: governance.metadata.authority,
          owner: governance.metadata.owner,
          status: governance.metadata.status,
          freshness: governance.metadata.freshness,
          tags: extractTags(content, relPath),
        });
      } catch (err) {
        if (!(err instanceof ParseError)) throw err;
      }
    })
  );

  parsed.sort(compareDocs);
  return parsed;
}

async function collectApprovedTags(repoRoot) {
  const relPath = 'docs/governance/tags-catalogue.md';
  const path = resolve(repoRoot, relPath);
  if (!existsSync(path)) return new Set();
  const content = await readFile(path, 'utf8');
  const ast = unified().use(remarkParse).use(remarkGfm).parse(content);
  const approved = new Set();

  let inCatalogue = false;
  for (const node of ast.children) {
    if (node.type === 'heading' && node.depth === 2) {
      const text = node.children
        .map((child) => (child.type === 'text' ? child.value : ''))
        .join('')
        .trim();
      inCatalogue = text.toLowerCase() === 'catalogue';
      continue;
    }
    if (!inCatalogue || node.type !== 'table') continue;
    for (let i = 1; i < node.children.length; i += 1) {
      const tagCell = node.children[i].children[0];
      if (!tagCell) continue;
      visit(tagCell, 'inlineCode', (codeNode) => {
        const tag = codeNode.value.trim();
        if (tag) approved.add(tag);
      });
    }
  }
  return approved;
}

function extractTags(content, relPath) {
  const tags = new Set();
  for (const match of content.matchAll(TAG_LINE_RE)) {
    for (const raw of match[1].split(',')) {
      const tag = stripInlineCode(raw.trim());
      if (!tag) continue;
      tags.add(tag);
    }
  }
  return [...tags].sort().map((tag) => {
    if (tag && !/^[a-z0-9]+(-[a-z0-9]+)*$/.test(tag)) {
      findings.push({
        severity: 'ERROR',
        file: relPath,
        line: 1,
        message: `malformed tag "${tag}" in governed document`,
      });
    }
    return tag;
  });
}

function stripInlineCode(value) {
  if (value.length >= 2 && value.startsWith('`') && value.endsWith('`')) {
    return value.slice(1, -1).trim();
  }
  return value;
}

function renderIndexes(items, approvedTags) {
  const outputs = new Map();
  outputs.set(
    'README.md',
    renderPage({
      title: 'Documentation Indexes',
      type: 'Guide',
      owner: 'Docs governance',
      status: 'Live',
      upstream: 'docs/guides/documentation-governance.md, scripts/docs/docs-index.mjs',
      downstream: 'pnpm docs:index:check, pnpm docs:check',
      body: [
        'Generated documentation indexes are discovery surfaces over governed documents.',
        '',
        renderTable(
          ['Index', 'Description'],
          [
            ['[By type](by-type.md)', 'Governed documents grouped by document type.'],
            ['[By authority](by-authority.md)', 'Governed documents grouped by authority level.'],
            ['[By owner](by-owner.md)', 'Governed documents grouped by owner.'],
            ['[By status](by-status.md)', 'Governed documents grouped by lifecycle status.'],
            [
              '[By tag](by-tag.md)',
              'Governed documents grouped by approved tag usage where available.',
            ],
          ]
        ),
      ].join('\n'),
    })
  );
  outputs.set('by-type.md', renderGroupedPage('Documentation By Type', 'type', items));
  outputs.set(
    'by-authority.md',
    renderGroupedPage('Documentation By Authority', 'authority', items)
  );
  outputs.set('by-owner.md', renderGroupedPage('Documentation By Owner', 'owner', items));
  outputs.set('by-status.md', renderGroupedPage('Documentation By Status', 'status', items));
  outputs.set('by-tag.md', renderTagPage(items, approvedTags));
  return outputs;
}

function renderGroupedPage(title, field, items) {
  const groups = groupBy(items, (item) => item[field]);
  const sections = [...groups.keys()].sort().map((group) => {
    return [`## ${group}`, '', renderDocsTable(groups.get(group))].join('\n');
  });
  return renderPage({
    title,
    type: 'Guide',
    owner: 'Docs governance',
    status: 'Live',
    upstream: 'docs/guides/documentation-governance.md, scripts/docs/docs-index.mjs',
    downstream: 'pnpm docs:index:check, pnpm docs:check',
    body: sections.join('\n\n'),
  });
}

function renderTagPage(items, approvedTags) {
  const groups = new Map();
  for (const item of items) {
    for (const tag of item.tags) {
      if (!approvedTags.has(tag)) {
        findings.push({
          severity: 'ERROR',
          file: item.path,
          line: 1,
          message: `unknown tag "${tag}"; add it to docs/governance/tags-catalogue.md or remove it`,
        });
      }
      if (!groups.has(tag)) groups.set(tag, []);
      groups.get(tag).push(item);
    }
  }

  const body =
    groups.size === 0
      ? 'No tagged governed documents found.'
      : [...groups.keys()]
          .sort()
          .map((tag) => [`## ${tag}`, '', renderDocsTable(groups.get(tag))].join('\n'))
          .join('\n\n');

  return renderPage({
    title: 'Documentation By Tag',
    type: 'Guide',
    owner: 'Docs governance',
    status: 'Live',
    upstream:
      'docs/guides/documentation-governance.md, docs/governance/tags-catalogue.md, scripts/docs/docs-index.mjs',
    downstream: 'pnpm docs:index:check, pnpm docs:check',
    body,
  });
}

function renderPage({ title, type, owner, status, upstream, downstream, body }) {
  const metadata = renderTable(
    ['Type', 'Authority', 'Owner', 'Status', 'Freshness'],
    [
      [
        type,
        'Derived',
        owner,
        status,
        'Generated from governed document metadata by `scripts/docs/docs-index.mjs`',
      ],
    ]
  );
  const relations = renderTable(['Upstream', 'Downstream'], [[upstream, downstream]]);

  return `# ${title}

${metadata}

${relations}

${GENERATED_MARKER}

${body}
`;
}

function renderDocsTable(items) {
  const rows = items
    .slice()
    .sort(compareDocs)
    .map((item) => [
      `[${escapeTable(item.title)}](../../${item.path})`,
      `\`${item.path}\``,
      escapeTable(item.type),
      escapeTable(item.authority),
      escapeTable(item.owner),
      escapeTable(item.status),
    ]);
  return renderTable(['Document', 'Path', 'Type', 'Authority', 'Owner', 'Status'], rows);
}

function renderTable(headers, rows) {
  const widths = headers.map((header, index) => {
    const cellWidths = rows.map((row) => row[index].length);
    return Math.max(header.length, 3, ...cellWidths);
  });
  const renderRow = (cells) => {
    return `| ${cells.map((cell, index) => cell.padEnd(widths[index])).join(' | ')} |`;
  };
  const separator = `| ${widths.map((width) => '-'.repeat(width)).join(' | ')} |`;
  return [renderRow(headers), separator, ...rows.map(renderRow)].join('\n');
}

function groupBy(items, keyFn) {
  const groups = new Map();
  for (const item of items) {
    const key = keyFn(item);
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(item);
  }
  return groups;
}

async function checkOutputs(outputs) {
  for (const file of INDEX_FILES) {
    const relPath = `${INDEX_DIR}/${file}`;
    const expected = outputs.get(file);
    const absPath = resolve(root, relPath);
    if (!existsSync(absPath)) {
      findings.push({
        severity: 'ERROR',
        file: relPath,
        line: 1,
        message: 'generated index is missing; run pnpm docs:index',
      });
      continue;
    }
    const actual = await readFile(absPath, 'utf8');
    if (actual !== expected) {
      findings.push({
        severity: 'ERROR',
        file: relPath,
        line: 1,
        message: 'generated index is stale; run pnpm docs:index',
      });
    }
  }
}

async function writeOutputs(outputs) {
  for (const [file, content] of outputs) {
    const relPath = `${INDEX_DIR}/${file}`;
    const absPath = resolve(root, relPath);
    mkdirSync(dirname(absPath), { recursive: true });
    await writeFile(absPath, content, 'utf8');
  }
}

function compareDocs(a, b) {
  return compareStrings(a.title, b.title) || compareStrings(a.path, b.path);
}

function compareStrings(a, b) {
  const minLength = Math.min(a.length, b.length);
  for (let i = 0; i < minLength; i += 1) {
    const diff = a.charCodeAt(i) - b.charCodeAt(i);
    if (diff !== 0) return diff;
  }
  return a.length - b.length;
}

function escapeTable(value) {
  return value.replaceAll('|', '\\|').replaceAll('\n', ' ');
}
